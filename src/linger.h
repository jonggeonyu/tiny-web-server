/*
 * linger: "부드럽게 닫기"를 전담하는 스레드 하나.
 *
 * 문제: 에러 응답 뒤 부드럽게 닫기(남은 입력을 읽어 버리며 상대가 닫기를 기다림)는 최대 2초 걸린다.
 *       일꾼이 직접 하면 그동안 일꾼 하나가 아무 일도 못 하고 묶인다.
 * 해결: 일꾼은 쓰기 방향만 닫고(shutdown) fd 를 이 스레드에 넘긴 뒤 바로 다음 일로 간다.
 *       이 스레드는 poll 로 여러 fd 를 한꺼번에 지켜보다가, 상대가 닫거나 시간이 다 되면 close 한다.
 *       (fd 여러 개를 스레드 하나가 돌보는 방식 = 작은 "이벤트 루프")
 */
#ifndef LINGER_H
#define LINGER_H

/* 전용 스레드 시작. 반환: 0 / -1 */
int linger_start(void);

/* fd 를 부드럽게 닫는다. 기다리지 않고 바로 돌아온다.
 * 전용 스레드가 없거나(단위 테스트) 맡은 연결이 LINGER_MAX 개로 가득 차면:
 *   - 스레드 없음 → 이 자리에서 직접 부드럽게 닫기 (기다림)
 *   - 가득 참     → 그냥 닫기 (일꾼을 묶지 않는 것이 우선) */
void linger_close(int fd);

/* 전용 스레드를 멈추고, 맡고 있던 fd 를 모두 닫는다 */
void linger_stop(void);

#endif /* LINGER_H */
